package com.zlp.api;

public class ApiEntity {

    String apikey;
    String org_xid;
    String user_id;

    public String getApikey() {
        return apikey;
    }

    public void setApikey(String apikey) {
        this.apikey = apikey;
    }
    public String getOrg_xid() {
        return org_xid;
    }

    public void setOrg_xid(String org_xid) {
        this.org_xid = org_xid;
    }

    public String getUser_id() {
        return user_id;
    }

    public void setUser_id(String user_id) {
        this.user_id = user_id;
    }
}
